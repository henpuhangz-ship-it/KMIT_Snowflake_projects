CREATE TABLE FACT_PATIENT_ADMISSION_LIFECYCLE
(
    ENCOUNTER_ID VARCHAR,
    PATIENT_ID VARCHAR,
    TRIAGE_DATE DATE,
    ADMISSION_DATE DATE,
    DISCHARGE_DATE DATE,
    TRIAGE_TO_ADMIT_DAYS NUMBER,
    LENGTH_OF_STAY_DAYS NUMBER
);
INSERT INTO FACT_PATIENT_ADMISSION_LIFECYCLE
(
    ENCOUNTER_ID,
    PATIENT_ID,
    TRIAGE_DATE,
    ADMISSION_DATE,
    DISCHARGE_DATE,
    TRIAGE_TO_ADMIT_DAYS,
    LENGTH_OF_STAY_DAYS
)
SELECT
    ENCOUNTER_ID,
    PATIENT_ID,
    TRIAGE_DATE,
    ADMISSION_DATE,
    DISCHARGE_DATE,
    DATEDIFF('DAY', TRIAGE_DATE, ADMISSION_DATE) AS TRIAGE_TO_ADMIT_DAYS,
    DATEDIFF('DAY', ADMISSION_DATE, DISCHARGE_DATE) AS LENGTH_OF_STAY_DAYS
FROM RAW_PATIENT_JOURNEY;

SELECT
    ENCOUNTER_ID,
    PATIENT_ID,
    TRIAGE_TO_ADMIT_DAYS,
    LENGTH_OF_STAY_DAYS
FROM FACT_PATIENT_ADMISSION_LIFECYCLE
WHERE ADMISSION_DATE IS NOT NULL
  AND DISCHARGE_DATE IS NOT NULL
ORDER BY ENCOUNTER_ID;
