-----------TASK 2: Factless Coverage Analysis Query

SELECT
    DEPARTMENT_ID,
    COUNT(
        CASE
            WHEN SHIFT_TYPE='NIGHT'
            THEN 1
        END
    ) AS NIGHT_SHIFT_COUNT
FROM FACTLESS_STAFF_COVERAGE
WHERE SHIFT_DATE = '2026-08-20'
GROUP BY DEPARTMENT_ID
HAVING COUNT(
    CASE   
        WHEN SHIFT_TYPE = 'NIGHT' THEN 1
    END
) = 0;

