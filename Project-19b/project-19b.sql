CREATE OR REPLACE TABLE FACT_TREATMENT_BILLING
(
    claim_id varchar,
    encounter_id varchar,
    patient_id varchar,
    procedure_cost number(12,2),
    insurance_discount_pct number(5,2),
    copay_amount number(12,2),
    NET_CHARGE NUMBER(12,2)
);

INSERT INTO FACT_TREATMENT_BILLING
(
    CLAIM_ID,
    ENCOUNTER_ID,
    PATIENT_ID,
    PROCEDURE_COST,
    INSURANCE_DISCOUNT_PCT,
    COPAY_AMOUNT,
    NET_CHARGE
)
SELECT
    CLAIM_ID,
    ENCOUNTER_ID,
    PATIENT_ID,
    PROCEDURE_COST,
    INSURANCE_DISCOUNT_PCT,
    COPAY_AMOUNT,
    PROCEDURE_COST * (1-INSURANCE_DISCOUNT_PCT) - COPAY_AMOUNT AS NET_CHARGE
FROM
    RAW_TREATMENT_BILLS;

SELECT * FROM FACT_TREATMENT_BILLING;


SELECT * FROM RAW_TREATMENT_BILLS;

------------TASK 5---------------------------------

SELECT
    ENCOUNTER_ID,
    SUM(NET_CHARGE) AS TOTAL_NET_CHARGES,
    AVG(PROCEDURE_COST) AS AVG_PROCEDURE_COST
FROM FACT_TREATMENT_BILLING
GROUP BY ENCOUNTER_ID
ORDER BY ENCOUNTER_ID;

