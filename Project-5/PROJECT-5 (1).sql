/*=============================
CATEGORY-WISE REVENUE
==============================*/

SELECT
    p.CATEGORY,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM RETAIL_SCHEMA.FACT_SALES f
JOIN RETAIL_SCHEMA.DIM_PRODUCT p
    ON f.PRODUCT_ID = p.PRODUCT_ID
GROUP BY p.CATEGORY
ORDER BY TOTAL_REVENUE DESC;

/*=============================
CUSTOMER PURCHASE TREND
==============================*/

SELECT
    c.CUSTOMER_NAME,
    d.YEAR,
    d.MONTH,
    COUNT(f.SALE_ID)    AS NUM_PURCHASES,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_SPEND
FROM RETAIL_SCHEMA.FACT_SALES f
JOIN RETAIL_SCHEMA.DIM_CUSTOMER c ON f.CUSTOMER_ID = c.CUSTOMER_ID
JOIN RETAIL_SCHEMA.DIM_DATE d     ON f.DATE_ID     = d.DATE_ID
GROUP BY c.CUSTOMER_NAME, d.YEAR, d.MONTH
ORDER BY c.CUSTOMER_NAME, d.YEAR, d.MONTH;

/*=============================
PRODUCT PERFORMANCE DASHBOARD
==============================*/

SELECT
    p.PRODUCT_NAME,
    p.CATEGORY,
    p.BRAND,
    SUM(f.QUANTITY)               AS TOTAL_UNITS_SOLD,
    SUM(f.TOTAL_AMOUNT)           AS TOTAL_REVENUE,
    COUNT(DISTINCT f.CUSTOMER_ID) AS UNIQUE_BUYERS
FROM RETAIL_SCHEMA.FACT_SALES f
JOIN RETAIL_SCHEMA.DIM_PRODUCT p
    ON f.PRODUCT_ID = p.PRODUCT_ID
GROUP BY p.PRODUCT_NAME, p.CATEGORY, p.BRAND
ORDER BY TOTAL_REVENUE DESC;

/*=============================
BRANCH PERFORMANCE DASHBOARD
==============================*/

SELECT
    b.BRANCH_NAME,
    b.REGION,
    b.MANAGER_NAME,
    COUNT(f.SALE_ID)              AS TOTAL_TRANSACTIONS,
    SUM(f.TOTAL_AMOUNT)           AS TOTAL_REVENUE,
    COUNT(DISTINCT f.CUSTOMER_ID) AS UNIQUE_CUSTOMERS
FROM RETAIL_SCHEMA.FACT_SALES f
JOIN RETAIL_SCHEMA.DIM_BRANCH b
    ON f.BRANCH_ID = b.BRANCH_ID
GROUP BY b.BRANCH_NAME, b.REGION, b.MANAGER_NAME
ORDER BY TOTAL_REVENUE DESC;

/*=============================
REGIONAL SALES ANALYSIS
==============================*/

SELECT
    b.REGION,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM RETAIL_SCHEMA.FACT_SALES f
JOIN RETAIL_SCHEMA.DIM_BRANCH b
    ON f.BRANCH_ID = b.BRANCH_ID
GROUP BY b.REGION
ORDER BY TOTAL_REVENUE DESC;

/*=============================
SALES TREND ANALYSIS
==============================*/

SELECT
    d.DATE,
    d.DAY_NAME,
    d.IS_WEEKEND,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE,
    COUNT(f.SALE_ID)    AS TOTAL_TRANSACTIONS
FROM RETAIL_SCHEMA.FACT_SALES f
JOIN RETAIL_SCHEMA.DIM_DATE d
    ON f.DATE_ID = d.DATE_ID
GROUP BY d.DATE, d.DAY_NAME, d.IS_WEEKEND
ORDER BY d.DATE;
