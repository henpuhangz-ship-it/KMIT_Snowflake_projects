-- ============================================

CREATE OR REPLACE TABLE RETAIL_SCHEMA.FACT_SALES (
    SALE_ID         NUMBER PRIMARY KEY,

    CUSTOMER_ID     NUMBER,
    PRODUCT_ID      NUMBER,
    BRANCH_ID       NUMBER,
    DATE_ID         NUMBER,

    QUANTITY        NUMBER,
    TOTAL_AMOUNT    NUMBER(12,2),

    FOREIGN KEY (CUSTOMER_ID)
        REFERENCES RETAIL_SCHEMA.DIM_CUSTOMER(CUSTOMER_ID),

    FOREIGN KEY (PRODUCT_ID)
        REFERENCES RETAIL_SCHEMA.DIM_PRODUCT(PRODUCT_ID),

    FOREIGN KEY (BRANCH_ID)
        REFERENCES RETAIL_SCHEMA.DIM_BRANCH(BRANCH_ID),

    FOREIGN KEY (DATE_ID)
        REFERENCES RETAIL_SCHEMA.DIM_DATE(DATE_ID)
);

INSERT INTO RETAIL_SCHEMA.FACT_SALES
SELECT
    SALE_ID,
    CUSTOMER_ID,
    PRODUCT_ID,
    BRANCH_ID,
    DATE_ID,
    QUANTITY,
    TOTAL_AMOUNT
FROM RETAIL_RAW.RAW_SALES;

SELECT * FROM RETAIL_SCHEMA.FACT_SALES;

SELECT COUNT(*) FROM RETAIL_SCHEMA.DIM_CUSTOMER;
SELECT COUNT(*) FROM RETAIL_SCHEMA.DIM_PRODUCT;
SELECT COUNT(*) FROM RETAIL_SCHEMA.DIM_BRANCH;
SELECT COUNT(*) FROM RETAIL_SCHEMA.DIM_DATE;
SELECT COUNT(*) FROM RETAIL_SCHEMA.FACT_SALES;

/*=============================
CUSTOMER-WISE SALES REPORT
==============================*/

SELECT
    c.CUSTOMER_NAME,
    c.STATE,
    c.MEMBERSHIP,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM RETAIL_SCHEMA.FACT_SALES f
JOIN RETAIL_SCHEMA.DIM_CUSTOMER c
    ON f.CUSTOMER_ID = c.CUSTOMER_ID
GROUP BY c.CUSTOMER_NAME, c.STATE, c.MEMBERSHIP
ORDER BY TOTAL_REVENUE DESC;

/*=============================
PRODUCT-WISE REVENUE REPORT
==============================*/

SELECT
    p.PRODUCT_NAME,
    p.CATEGORY,
    p.BRAND,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM RETAIL_SCHEMA.FACT_SALES f
JOIN RETAIL_SCHEMA.DIM_PRODUCT p
    ON f.PRODUCT_ID = p.PRODUCT_ID
GROUP BY p.PRODUCT_NAME, p.CATEGORY, p.BRAND
ORDER BY TOTAL_REVENUE DESC;

/*=============================
BRANCH-WISE REVENUE REPORT
==============================*/

SELECT
    b.BRANCH_NAME,
    b.CITY,
    b.STATE,
    b.REGION,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM RETAIL_SCHEMA.FACT_SALES f
JOIN RETAIL_SCHEMA.DIM_BRANCH b
    ON f.BRANCH_ID = b.BRANCH_ID
GROUP BY b.BRANCH_NAME, b.CITY, b.STATE, b.REGION
ORDER BY TOTAL_REVENUE DESC;

/*=============================
STATE-WISE REVENUE REPORT
==============================*/

SELECT
    b.STATE,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM RETAIL_SCHEMA.FACT_SALES f
JOIN RETAIL_SCHEMA.DIM_BRANCH b
    ON f.BRANCH_ID = b.BRANCH_ID
GROUP BY b.STATE
ORDER BY TOTAL_REVENUE DESC;

/*=============================
MONTHLY REVENUE REPORT
==============================*/

SELECT
    d.YEAR,
    d.MONTH,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM RETAIL_SCHEMA.FACT_SALES f
JOIN RETAIL_SCHEMA.DIM_DATE d
    ON f.DATE_ID = d.DATE_ID
GROUP BY d.YEAR, d.MONTH
ORDER BY d.YEAR, d.MONTH;

/*=============================
QUARTERLY REVENUE REPORT
==============================*/

SELECT
    d.YEAR,
    d.QUARTER,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM RETAIL_SCHEMA.FACT_SALES f
JOIN RETAIL_SCHEMA.DIM_DATE d
    ON f.DATE_ID = d.DATE_ID
GROUP BY d.YEAR, d.QUARTER
ORDER BY d.YEAR, d.QUARTER;

/*=============================
TOP 10 CUSTOMERS
==============================*/

