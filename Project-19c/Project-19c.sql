-- TASK 4: LOAN APPLICATION ACCUMULATING SNAPSHOT


CREATE OR REPLACE TABLE FACT_CREDIT_APPROVAL_LIFECYCLE
(
    APP_ID VARCHAR,
    SUBMISSION_DATE DATE,
    UNDERWRITE_DATE DATE,
    RISK_APPROVAL_DATE DATE,
    DISBURSEMENT_DATE DATE,
    UNDERWRITE_DAYS NUMBER,
    RISK_APPROVAL_DAYS NUMBER,
    DISBURSEMENT_DAYS NUMBER,
    TOTAL_CYCLE_DAYS NUMBER
);


INSERT INTO FACT_CREDIT_APPROVAL_LIFECYCLE
(
    APP_ID,
    SUBMISSION_DATE,
    UNDERWRITE_DATE,
    RISK_APPROVAL_DATE,
    DISBURSEMENT_DATE,
    UNDERWRITE_DAYS,
    RISK_APPROVAL_DAYS,
    DISBURSEMENT_DAYS,
    TOTAL_CYCLE_DAYS
)
SELECT
    APP_ID,
    SUBMISSION_DATE,
    UNDERWRITE_DATE,
    RISK_APPROVAL_DATE,
    DISBURSEMENT_DATE,
    DATEDIFF('DAY', SUBMISSION_DATE, UNDERWRITE_DATE)
        AS UNDERWRITE_DAYS,
    DATEDIFF('DAY', UNDERWRITE_DATE, RISK_APPROVAL_DATE)
        AS RISK_APPROVAL_DAYS,
    DATEDIFF('DAY', RISK_APPROVAL_DATE, DISBURSEMENT_DATE)
        AS DISBURSEMENT_DAYS,
    DATEDIFF('DAY', SUBMISSION_DATE, DISBURSEMENT_DATE)
        AS TOTAL_CYCLE_DAYS
FROM RAW_CREDIT_LIFECYCLES
WHERE DISBURSEMENT_DATE IS NOT NULL;


SELECT *
FROM FACT_CREDIT_APPROVAL_LIFECYCLE
ORDER BY APP_ID;



-- TASK 5: BOTTLENECK STAGE IDENTIFICATION


SELECT
    APP_ID,
    SUBMISSION_DATE,
    CASE
        WHEN UNDERWRITE_DATE IS NULL
            THEN 'AWAITING_UNDERWRITE'

        WHEN RISK_APPROVAL_DATE IS NULL
            THEN 'AWAITING_RISK_AUTH'

        WHEN DISBURSEMENT_DATE IS NULL
            THEN 'AWAITING_DISBURSAL'
    END AS CURRENT_BOTTLENECK
FROM RAW_CREDIT_LIFECYCLES
WHERE DISBURSEMENT_DATE IS NULL
ORDER BY APP_ID;


-- TASK 6: FACTLESS COMPLIANCE AUDIT COVERAGE


CREATE OR REPLACE TABLE FACTLESS_COMPLIANCE_AUDIT_COVERAGE
(
    AUDIT_YEAR NUMBER,
    QUARTER VARCHAR,
    ACCOUNT_ID VARCHAR,
    AUDITOR_FIRM VARCHAR,
    COMPLIANCE_STATUS VARCHAR
);


INSERT INTO FACTLESS_COMPLIANCE_AUDIT_COVERAGE
(
    AUDIT_YEAR,
    QUARTER,
    ACCOUNT_ID,
    AUDITOR_FIRM,
    COMPLIANCE_STATUS
)
SELECT
    AUDIT_YEAR,
    QUARTER,
    ACCOUNT_ID,
    AUDITOR_FIRM,
    COMPLIANCE_STATUS
FROM RAW_AUDIT_COVERAGE;


-- Accounts that processed HIGH-RISK transfers
-- and their 2026 audit coverage

SELECT
    F.SENDER_ACC AS ACCOUNT_ID,
    COUNT(*) AS HIGH_RISK_TXN_COUNT,
    CASE
        WHEN A.ACCOUNT_ID IS NOT NULL
            THEN 'AUDITED'
        ELSE 'NOT_AUDITED'
    END AS COMPLIANCE_STATUS
FROM FACT_WIRE_TRANSFERS F
LEFT JOIN FACTLESS_COMPLIANCE_AUDIT_COVERAGE A
    ON F.SENDER_ACC = A.ACCOUNT_ID
    AND A.AUDIT_YEAR = 2026
JOIN DIM_WIRE_ATTRIBUTES D
    ON F.ATTRIBUTE_SK = D.ATTRIBUTE_SK
WHERE D.RISK_FLAG = 'HIGH'
GROUP BY
    F.SENDER_ACC,
    CASE
        WHEN A.ACCOUNT_ID IS NOT NULL
            THEN 'AUDITED'
        ELSE 'NOT_AUDITED'
    END
ORDER BY ACCOUNT_ID;



-- TASK 7: RISK PROFILE REVENUE CROSS-ANALYSIS


SELECT
    D.RISK_FLAG,
    D.TRANSFER_TYPE,
    COUNT(*) AS TOTAL_TXNS,
    SUM(F.FEE) AS TOTAL_FEES,
    SUM(F.BASE_AMOUNT_USD) AS TOTAL_VOLUME_USD
FROM FACT_WIRE_TRANSFERS F
JOIN DIM_WIRE_ATTRIBUTES D
    ON F.ATTRIBUTE_SK = D.ATTRIBUTE_SK
GROUP BY
    D.RISK_FLAG,
    D.TRANSFER_TYPE
ORDER BY
    D.RISK_FLAG,
    D.TRANSFER_TYPE;


-- TASK 8: MULTI-FACT COMPREHENSIVE RECONCILIATION AUDIT


SELECT
    (
        SELECT SUM(BASE_AMOUNT_USD)
        FROM FACT_WIRE_TRANSFERS
    ) AS TOTAL_WIRE_VOL_USD,

    (
        SELECT SUM(CLOSING_BALANCE)
        FROM FACT_VAULT_CASH_SNAPSHOT
        WHERE SNAPSHOT_DATE = '2026-08-25'
    ) AS VAULT_CLOSING_USD,

    (
        SELECT COUNT(*)
        FROM FACT_CREDIT_APPROVAL_LIFECYCLE
    ) AS COMPLETED_LOAN_APPS,

    CASE
        WHEN
            (
                SELECT SUM(BASE_AMOUNT_USD)
                FROM FACT_WIRE_TRANSFERS
            ) = 2286500.00

            AND

            (
                SELECT SUM(CLOSING_BALANCE)
                FROM FACT_VAULT_CASH_SNAPSHOT
                WHERE SNAPSHOT_DATE = '2026-08-25'
            ) = 16400000.00

            AND

            (
                SELECT COUNT(*)
                FROM FACT_CREDIT_APPROVAL_LIFECYCLE
            ) = 2

        THEN TRUE
        ELSE FALSE
    END AS AUDIT_SANITY_FLAG;