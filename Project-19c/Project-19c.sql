-- TASK 2: WIRE TRANSFER FACT TABLE

CREATE OR REPLACE TABLE FACT_WIRE_TRANSFERS
(
    TXN_ID VARCHAR,
    TXN_DATE DATE,
    SENDER_ACC VARCHAR,
    RECEIVER_ACC VARCHAR,
    ATTRIBUTE_SK NUMBER,
    AMOUNT NUMBER(18,2),
    FEE NUMBER(18,2),
    CURRENCY_RATE NUMBER(10,4),
    BASE_AMOUNT_USD NUMBER(18,2),
    NET_TRANSFER_VAL NUMBER(18,2)
);


INSERT INTO FACT_WIRE_TRANSFERS
(
    TXN_ID,
    TXN_DATE,
    SENDER_ACC,
    RECEIVER_ACC,
    ATTRIBUTE_SK,
    AMOUNT,
    FEE,
    CURRENCY_RATE,
    BASE_AMOUNT_USD,
    NET_TRANSFER_VAL
)
SELECT
    R.TXN_ID,
    R.TXN_DATE,
    R.SENDER_ACC,
    R.RECEIVER_ACC,
    D.ATTRIBUTE_SK,
    R.AMOUNT,
    R.FEE,
    R.CURRENCY_RATE,
    R.AMOUNT * R.CURRENCY_RATE AS BASE_AMOUNT_USD,
    (R.AMOUNT * R.CURRENCY_RATE) - R.FEE AS NET_TRANSFER_VAL
FROM RAW_WIRE_TRANSFERS R
JOIN DIM_WIRE_ATTRIBUTES D
    ON R.AUTH_METHOD = D.AUTH_METHOD
    AND R.RISK_FLAG = D.RISK_FLAG
    AND R.TRANSFER_TYPE = D.TRANSFER_TYPE;


SELECT *
FROM FACT_WIRE_TRANSFERS
ORDER BY TXN_ID;


