    SELECT DISTINCT CATEGORY
    FROM RAW_PRODUCTS
);

/*-----DIM BRAND---------*/
CREATE TABLE DIM_BRAND(
    BRAND_ID NUMBER PRIMARY KEY,
    BRAND_NAME VARCHAR,
    CATEGORY_ID NUMBER,
    FOREIGN KEY (CATEGORY_ID) REFERENCES DIM_CATEGORY(CATEGORY_ID)
);

INSERT INTO DIM_BRAND(
    BRAND_ID,
    BRAND_NAME,
    CATEGORY_ID
)
SELECT
    ROW_NUMBER() OVER(ORDER BY P.BRAND),
    P.BRAND,
    C.CATEGORY_ID
    FROM(
        SELECT DISTINCT BRAND, CATEGORY
        FROM RAW_PRODUCTS P
    )P
JOIN DIM_CATEGORY C
            ON P.CATEGORY = C.CATEGORY_NAME;



/*-----DIM PRODUCT---------*/

CREATE TABLE DIM_PRODUCT(
    PRODUCT_ID      NUMBER PRIMARY KEY,
    PRODUCT_NAME    VARCHAR,
    PRICE           NUMBER,
    BRAND_ID        NUMBER,
    FOREIGN KEY (BRAND_ID) REFERENCES DIM_BRAND(BRAND_ID)
);

INSERT INTO DIM_PRODUCT(
    PRODUCT_ID,
    PRODUCT_NAME,
    PRICE,
    BRAND_ID
)
SELECT
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    P.PRICE,
    B.BRAND_ID
FROM RAW_PRODUCTS P
JOIN DIM_BRAND B
    ON P.BRAND = B.BRAND_NAME
JOIN DIM_CATEGORY C
    ON P.CATEGORY = C.CATEGORY_NAME
    AND B.CATEGORY_ID = C.CATEGORY_ID;

