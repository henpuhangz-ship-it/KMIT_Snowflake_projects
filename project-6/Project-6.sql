CREATE TABLE DIM_BRANCH (
    BRANCH_ID NUMBER PRIMARY KEY,
    BRANCH_NAME VARCHAR,
    MANAGER_NAME VARCHAR,
    CITY_ID NUMBER,
    FOREIGN KEY (CITY_ID) REFERENCES DIM_CITY(CITY_ID)
);

INSERT INTO DIM_BRANCH(
    BRANCH_ID,
    BRANCH_NAME,
    MANAGER_NAME,
    CITY_ID
)
SELECT
    B.BRANCH_ID,
    B.BRANCH_NAME,
    B.MANAGER_NAME,
    CI.CITY_ID    
FROM RAW_BRANCHES B
JOIN DIM_CITY CI
    ON B.CITY = CI.CITY_NAME
JOIN DIM_STATE S
    ON B.STATE = S.STATE_NAME
   AND CI.STATE_ID = S.STATE_ID;

