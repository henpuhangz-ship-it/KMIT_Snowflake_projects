CREATE TABLE DIM_QUARTER (
    QUARTER_ID   NUMBER PRIMARY KEY,
    QUARTER_NAME VARCHAR,
    YEAR_ID      NUMBER,
    FOREIGN KEY (YEAR_ID) REFERENCES DIM_YEAR(YEAR_ID)
);

INSERT INTO DIM_QUARTER (
    QUARTER_ID,
    QUARTER_NAME,
    YEAR_ID
)
SELECT DISTINCT
    ROW_NUMBER() OVER (ORDER BY C.YEAR, C.QUARTER),
    C.QUARTER,
    Y.YEAR_ID
FROM RAW_CALENDAR C
JOIN DIM_YEAR Y
    ON C.YEAR = Y.YEAR_VALUE;

SELECT * FROM DIM_QUARTER
ORDER BY YEAR_ID, QUARTER_ID;


/*---------------- DIM MONTH ----------------*/

CREATE TABLE DIM_MONTH (
    MONTH_ID     NUMBER PRIMARY KEY,
    MONTH_NAME   VARCHAR,
    QUARTER_ID   NUMBER,
    FOREIGN KEY (QUARTER_ID) REFERENCES DIM_QUARTER(QUARTER_ID)
);

INSERT INTO DIM_MONTH (
    MONTH_ID,
    MONTH_NAME,
    QUARTER_ID
)
SELECT DISTINCT
    ROW_NUMBER() OVER (ORDER BY C.YEAR, C.QUARTER, C.MONTH),
    C.MONTH,
    Q.QUARTER_ID
FROM RAW_CALENDAR C
JOIN DIM_QUARTER Q
    ON C.QUARTER = Q.QUARTER_NAME
JOIN DIM_YEAR Y
    ON C.YEAR = Y.YEAR_VALUE
   AND Q.YEAR_ID = Y.YEAR_ID;

SELECT * FROM DIM_MONTH
ORDER BY MONTH_ID;


