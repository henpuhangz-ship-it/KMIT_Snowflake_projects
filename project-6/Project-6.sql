CREATE TABLE DIM_STATE (
    STATE_ID       NUMBER PRIMARY KEY,
    STATE_NAME     VARCHAR,
    REGION_ID      NUMBER,
    FOREIGN KEY (REGION_ID) REFERENCES DIM_REGION(REGION_ID)
);
SELECT * FROM DIM_STATE;

INSERT INTO DIM_STATE (STATE_ID, STATE_NAME, REGION_ID)
SELECT
    ROW_NUMBER() OVER (ORDER BY STATE),
    STATE,
    REGION_ID
FROM (
    SELECT
        STATE,
        MAX(REGION_ID) AS REGION_ID
    FROM (
        SELECT STATE, R.REGION_ID
        FROM RAW_BRANCHES B
        JOIN DIM_REGION R
            ON B.REGION = R.REGION_NAME

        UNION ALL

        SELECT STATE, NULL AS REGION_ID
        FROM RAW_CUSTOMERS
    )
    GROUP BY STATE
) S;


SELECT * FROM DIM_STATE;





CREATE TABLE DIM_CITY (
    CITY_ID        NUMBER PRIMARY KEY,
    CITY_NAME      VARCHAR,
    STATE_ID       NUMBER,
    FOREIGN KEY (STATE_ID) REFERENCES DIM_STATE(STATE_ID)
);

INSERT INTO DIM_CITY (CITY_ID, CITY_NAME, STATE_ID)
SELECT
    ROW_NUMBER() OVER (ORDER BY CITY),
    CITY,
    S.STATE_ID
FROM (
    SELECT DISTINCT CITY, STATE
    FROM RAW_CUSTOMERS

    UNION

    SELECT DISTINCT CITY, STATE
    FROM RAW_BRANCHES
) C
JOIN DIM_STATE S
    ON C.STATE = S.STATE_NAME;

SELECT * FROM DIM_CITY ORDER BY CITY_ID;


