/*Create a View named SALES_REPORT.*/
CREATE OR REPLACE VIEW SALES_REPORT AS
SELECT
    S.SALE_ID,
    S.SALE_DATE,

    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.MEMBERSHIP,

    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    P.CATEGORY,
    P.PRICE,

    B.BRANCH_ID,
    B.BRANCH_NAME,
    B.CITY AS BRANCH_CITY,

    S.QUANTITY,
    S.TOTAL_AMOUNT

FROM SALES S
JOIN CUSTOMERS C
    ON S.CUSTOMER_ID = C.CUSTOMER_ID
JOIN PRODUCTS P
    ON S.PRODUCT_ID = P.PRODUCT_ID
JOIN BRANCHES B
    ON S.BRANCH_ID = B.BRANCH_ID;
SELECT *
FROM SALES_REPORT;

/*Create a Materialized View named TOP_CUSTOMERS.*/
CREATE OR REPLACE MATERIALIZED VIEW TOP_CUSTOMERS AS
SELECT
    CUSTOMER_ID,
    SUM(TOTAL_AMOUNT) AS TOTAL_SPENDING
FROM SALES
GROUP BY CUSTOMER_ID;

SELECT *
FROM TOP_CUSTOMERS
ORDER BY TOTAL_SPENDING DESC;