/*TOTAL BUSINESS REVENUE*/
SELECT SUM(TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM SALES;

/*CUSTOMER WISE SAKES*/
SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.MEMBERSHIP,
    SUM(S.TOTAL_AMOUNT) AS TOTAL_SPENDING
FROM CUSTOMERS C
JOIN SALES S
    ON C.CUSTOMER_ID = S.CUSTOMER_ID
GROUP BY
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.MEMBERSHIP
ORDER BY TOTAL_SPENDING DESC;

/*BRANCH WISE SALES*/
SELECT
    B.BRANCH_ID,
    B.BRANCH_NAME,
    B.CITY,
    SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM BRANCHES B
JOIN SALES S
    ON B.BRANCH_ID = S.BRANCH_ID
GROUP BY
    B.BRANCH_ID,
    B.BRANCH_NAME,
    B.CITY
ORDER BY TOTAL_REVENUE DESC;

/*PRODUCT WISE SALES*/
