        WHEN
            (
                SELECT SUM(PAYLOAD:amount::NUMBER(18,2))
                FROM FINANCIAL_GOVERNANCE_DB.WEALTH_CORE.BRONZE_BANK_PAYLOADS
            )
            =
            (
                SELECT SUM(AMOUNT)
                FROM FINANCIAL_GOVERNANCE_DB.WEALTH_CORE.SILVER_BANK_TRANSACTIONS
