CREATE OR REPLACE ROW ACCESS POLICY RAP_REGION_POLICY
AS
(
    REGION_VALUE VARCHAR
)
RETURNS BOOLEAN
->
CASE

    WHEN IS_ROLE_IN_SESSION('COMPLIANCE_OFFICER')
        THEN TRUE

    WHEN IS_ROLE_IN_SESSION('NA_ANALYST')
         AND REGION_VALUE = 'NA'
        THEN TRUE

    WHEN IS_ROLE_IN_SESSION('EU_ANALYST')
         AND REGION_VALUE = 'EU'
        THEN TRUE

    ELSE FALSE

END;



