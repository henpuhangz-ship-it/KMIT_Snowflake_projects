CREATE OR REPLACE TABLE GOLD_EXTERNAL_AUDIT_AGGREGATE
(
    REGION              VARCHAR,
    TOTAL_SETTLED_VAL   NUMBER(18,2),
    SETTLED_TXN_COUNT   NUMBER,
    AVG_SETTLED_AMOUNT  NUMBER(18,2)
);



INSERT INTO GOLD_EXTERNAL_AUDIT_AGGREGATE
(
    REGION,
    TOTAL_SETTLED_VAL,
    SETTLED_TXN_COUNT,
    AVG_SETTLED_AMOUNT
)
SELECT
    REGION,
    SUM(AMOUNT),
    COUNT(*),
    ROUND(AVG(AMOUNT),2)
FROM SILVER_BANK_TRANSACTIONS
WHERE STATUS = 'SETTLED'
GROUP BY REGION;


CREATE OR REPLACE SECURE VIEW SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY
AS
SELECT
    REGION,
    TOTAL_SETTLED_VAL,
    SETTLED_TXN_COUNT,
    AVG_SETTLED_AMOUNT
FROM GOLD_EXTERNAL_AUDIT_AGGREGATE;

