--TASK 3 — DYNAMIC DATA MASKING

CREATE OR REPLACE MASKING POLICY MASK_SSN
AS
(
    VAL VARCHAR
)
RETURNS VARCHAR
->
CASE
    WHEN IS_ROLE_IN_SESSION('COMPLIANCE_OFFICER')
        THEN VAL
    ELSE
        '***-**-' || RIGHT(VAL,4)
END;



--------------------------------------------------------------------------------
-- MASK ACCOUNT NUMBER
--------------------------------------------------------------------------------

CREATE OR REPLACE MASKING POLICY MASK_ACCOUNT
AS
(
    VAL VARCHAR
)
RETURNS VARCHAR
->
CASE
    WHEN IS_ROLE_IN_SESSION('COMPLIANCE_OFFICER')
        THEN VAL
    ELSE
        'ACT-****'
END;



--------------------------------------------------------------------------------
-- APPLY MASKING POLICIES
--------------------------------------------------------------------------------

ALTER TABLE SILVER_BANK_TRANSACTIONS
